def main():
    conn = duckdb.connect(DB_PATH, read_only=True)
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "queries.jsonl")
    
    total = len(CASES)
    saved = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for idx, item in enumerate(CASES, 1):
            ids = []
            for pattern in item["expected_matches"]:
                sql = "SELECT id FROM datasets WHERE title LIKE ?"
                params = [pattern]
                if "id_pattern" in item:
                    sql += " AND id LIKE ?"
                    params.append(item["id_pattern"])
                rows = conn.execute(sql, params).fetchall()
                for r in rows:
                    if r[0] not in ids:
                        ids.append(r[0])
            
            if not ids:
                raise ValueError(f"No catalog matches found for query #{idx}: '{item['query']}'")
            
            entry = {
                "id": f"q{idx:03d}",
                "query": item["query"],
                "expected_ids": ids,
                "lang": item["lang"],
                "category": item["category"],
            }
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
            saved += 1
            
    print(f"Successfully generated {saved}/{total} eval queries into {out_path}")


if __name__ == "__main__":
    main()
